const loader = document.getElementById("loader");
const loaderPhrase = document.getElementById("loaderPhrase");
const langToggle = document.getElementById("langToggle");
const progressBar = document.getElementById("scrollProgress");
const cursorGlow = document.querySelector(".cursor-glow");
const heroShift = document.querySelector(".hero-shift");
const heroPanel = document.querySelector(".hero-panel");
let currentLang = localStorage.getItem("portfolio-lang") || "en";
let loaderInterval;

function runLoader(lang) {
  const phrases = loaderPhrases[lang] || loaderPhrases.en;
  let index = 0;
  if (loaderPhrase) loaderPhrase.textContent = phrases[0];
  clearInterval(loaderInterval);
  loaderInterval = setInterval(() => {
    index = (index + 1) % phrases.length;
    if (loaderPhrase) loaderPhrase.textContent = phrases[index];
  }, 360);
}

function applyLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    const value = translations[lang]?.[key];
    if (value) node.textContent = value;
  });
  if (langToggle) langToggle.textContent = lang === "en" ? "TR" : "EN";
  localStorage.setItem("portfolio-lang", lang);
  runLoader(lang);
}

langToggle?.addEventListener("click", () => {
  applyLanguage(currentLang === "en" ? "tr" : "en");
});

applyLanguage(currentLang);

document.getElementById("year").textContent = new Date().getFullYear();

window.addEventListener("load", () => {
  setTimeout(() => {
    clearInterval(loaderInterval);
    loader?.classList.add("hidden");
  }, 1450);
});

const revealObserver = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (entry.isIntersecting) {
      entry.target.classList.add("visible");
      revealObserver.unobserve(entry.target);
    }
  });
}, { threshold: 0.14 });

document.querySelectorAll(".reveal").forEach((el) => revealObserver.observe(el));

window.addEventListener("pointermove", (event) => {
  if (!cursorGlow) return;
  cursorGlow.animate({ left: `${event.clientX}px`, top: `${event.clientY}px` }, {
    duration: 700,
    fill: "forwards",
    easing: "cubic-bezier(.22,1,.36,1)"
  });
});

document.querySelectorAll(".spotlight-card").forEach((card) => {
  card.addEventListener("pointermove", (event) => {
    const rect = card.getBoundingClientRect();
    const x = ((event.clientX - rect.left) / rect.width) * 100;
    const y = ((event.clientY - rect.top) / rect.height) * 100;
    card.style.setProperty("--x", `${x}%`);
    card.style.setProperty("--y", `${y}%`);
  });
});

document.querySelectorAll(".magnetic").forEach((el) => {
  el.addEventListener("pointermove", (event) => {
    const rect = el.getBoundingClientRect();
    const x = event.clientX - rect.left - rect.width / 2;
    const y = event.clientY - rect.top - rect.height / 2;
    el.style.transform = `translate(${x * 0.08}px, ${y * 0.14}px)`;
  });
  el.addEventListener("pointerleave", () => {
    el.style.transform = "translate(0, 0)";
  });
});

document.querySelectorAll(".tilt-card").forEach((card) => {
  card.addEventListener("pointermove", (event) => {
    if (window.innerWidth < 900) return;
    const rect = card.getBoundingClientRect();
    const x = (event.clientX - rect.left) / rect.width - 0.5;
    const y = (event.clientY - rect.top) / rect.height - 0.5;
    card.style.transform = `perspective(1100px) rotateY(${x * 7}deg) rotateX(${-y * 7}deg) translateY(-2px)`;
  });
  card.addEventListener("pointerleave", () => {
    card.style.transform = "perspective(1100px) rotateY(0deg) rotateX(0deg) translateY(0px)";
  });
});

const counters = document.querySelectorAll('.count');
const counterObserver = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (!entry.isIntersecting) return;
    const el = entry.target;
    const end = Number(el.dataset.target || 0);
    let current = 0;
    const duration = 900;
    const start = performance.now();

    function tick(now) {
      const progress = Math.min((now - start) / duration, 1);
      current = Math.round(end * progress);
      el.textContent = current;
      if (progress < 1) requestAnimationFrame(tick);
    }

    requestAnimationFrame(tick);
    counterObserver.unobserve(el);
  });
}, { threshold: 0.7 });

counters.forEach((counter) => counterObserver.observe(counter));

function onScroll() {
  const scrollTop = window.scrollY;
  const maxScroll = document.documentElement.scrollHeight - window.innerHeight;
  const progress = maxScroll > 0 ? (scrollTop / maxScroll) * 100 : 0;
  if (progressBar) progressBar.style.height = `${progress}%`;

  const shiftAmount = Math.min(scrollTop * 0.06, 42);
  if (heroShift) heroShift.style.transform = `translateY(${shiftAmount * -0.18}px)`;
  if (heroPanel) heroPanel.style.transform = `translateY(${shiftAmount * 0.12}px)`;
}

window.addEventListener("scroll", onScroll, { passive: true });
onScroll();
